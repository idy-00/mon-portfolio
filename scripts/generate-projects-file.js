/**
 * Lit projects-base.js (données manuelles) + generated/projects-data.json (URLs live,
 * screenshots depuis GitHub/Cloudflare) et écrit src/data/projects.js prêt à bundler.
 * Appelé automatiquement par sync-projects.js avant npm run build.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { log } from './logger.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, '..')

export async function generateProjectsFile(generatedData) {
  // Load the base (manual) projects
  const basePath = path.join(ROOT, 'src', 'data', 'projects-base.js')
  const baseCode = fs.readFileSync(basePath, 'utf-8')

  // Build a map: repoName (lower) → { live, screenshot, deployment }
  const liveMap = {}
  for (const p of generatedData) {
    const key = (p.meta?.repoName || p.id?.replace('gh-', '') || '').toLowerCase()
    if (!key) continue
    liveMap[key] = {
      live: p.links?.live || null,
      screenshot: p.screenshots?.desktop
        ? `/generated/screenshots/${key}/desktop.webp`
        : null,
      screenshotTablet: p.screenshots?.tablet
        ? `/generated/screenshots/${key}/tablet.webp`
        : null,
      screenshotMobile: p.screenshots?.mobile
        ? `/generated/screenshots/${key}/mobile.webp`
        : null,
    }
  }

  log.info(`Live URL map: ${Object.keys(liveMap).length} entries`)
  Object.entries(liveMap).forEach(([k, v]) => {
    if (v.live) log.ok(`  ${k} → ${v.live}`)
  })

  // Dynamic import of base projects
  const baseModule = await import(`file://${basePath}?t=${Date.now()}`)
  const baseProjects = baseModule.manualProjects

  // Merge live URLs and screenshots into manual projects
  const merged = baseProjects.map(project => {
    const key = (project.repoName || '').toLowerCase()
    const live = liveMap[key]

    if (!live) return project

    return {
      ...project,
      live: project.live || live.live,         // manual live wins if already set
      screenshot: project.screenshot || live.screenshot,
    }
  })

  // Build auto projects from generated data that have no manual counterpart
  const manualRepoNames = new Set(
    baseProjects.map(p => (p.repoName || '').toLowerCase()).filter(Boolean)
  )
  const manualTitles = new Set(baseProjects.map(p => p.title.toLowerCase()))

  const autoProjects = generatedData
    .filter(p => {
      const repoName = (p.meta?.repoName || p.id?.replace('gh-', '') || '').toLowerCase()
      const title = (p.title || '').toLowerCase()
      return !manualRepoNames.has(repoName) && !manualTitles.has(title) && p.links?.live
    })
    .map((p, i) => {
      const repoName = (p.meta?.repoName || p.id?.replace('gh-', '') || '').toLowerCase()
      const slug = (p.title || repoName)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '')
      return {
        id: `auto-${i + 100}`,
        slug,
        repoName,
        title: p.title || repoName,
        category: p.category === 'frontend' ? 'Application Web' : p.category === 'backend' ? 'Backend' : 'Application Web',
        year: p.meta?.updatedAt?.slice(0, 4) || null,
        role: 'Développeur',
        duration: null,
        stack: p.stack || [],
        summary: p.summary || '',
        impact: null,
        features: [],
        challenge: null,
        link: p.links?.github || null,
        live: p.links?.live || null,
        screenshot: p.screenshots?.desktop ? `/generated/screenshots/${repoName}/desktop.webp` : null,
        source: 'auto',
      }
    })

  const allProjects = [...merged, ...autoProjects]

  // Serialize to JS module — no JSON.stringify tricks, write real JS
  const lines = [
    '// AUTO-GENERATED by scripts/generate-projects-file.js — do not edit manually',
    '// Edit src/data/projects-base.js for manual data, then run npm run sync-projects',
    '',
    'export const projects = ' + JSON.stringify(allProjects, null, 2),
    '',
    'export default projects',
  ]

  const outPath = path.join(ROOT, 'src', 'data', 'projects.js')
  fs.writeFileSync(outPath, lines.join('\n'), 'utf-8')

  const liveCount = allProjects.filter(p => p.live).length
  log.ok(`projects.js written — ${allProjects.length} projects, ${liveCount} with live URL`)

  return allProjects
}
